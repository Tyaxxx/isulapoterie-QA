/* Isula Poterie — gallery, slideshow, viewer, menu.
   Classic script (not a module) so that it also works from file://.
   The data comes from photos/photos.js (generated by update-photos.bat). */
(function () {
  "use strict";

  var SLIDE_MS = 3000;
  var SWIPE_PX = 50;
  var RESERVED_IDS = ["contenu", "accueil", "realisations", "contacts", "menu", "viewer", "slideshow"];
  var SVG_NS = "http://www.w3.org/2000/svg";

  var viewerDlg = document.getElementById("viewer");
  var menuDlg = document.getElementById("menu");

  function $(sel, root) { return (root || document).querySelector(sel); }
  function el(tag, cls, text) {
    var n = document.createElement(tag);
    if (cls) n.className = cls;
    if (text != null) n.textContent = text;
    return n;
  }
  function icon(id, size, cls) {
    var svg = document.createElementNS(SVG_NS, "svg");
    svg.setAttribute("aria-hidden", "true");
    if (cls) svg.setAttribute("class", cls);
    if (id === "i-logo") svg.setAttribute("viewBox", "0 0 820 2000");
    else { svg.setAttribute("width", size); svg.setAttribute("height", size); }
    var use = document.createElementNS(SVG_NS, "use");
    use.setAttribute("href", "#" + id);
    svg.appendChild(use);
    return svg;
  }
  function pad2(n) { return String(n).padStart(2, "0"); }
  function isOpen(d) { return !!(d && d.open); }

  /* ---------- data ---------- */
  var categories = [];
  var flat = [];
  (function readData() {
    var raw = window.ISULA_PHOTOS;
    var list = raw && Array.isArray(raw.categories) ? raw.categories : [];
    var used = {};
    list.forEach(function (c) {
      var photos = Array.isArray(c.photos) ? c.photos.filter(function (p) { return p && p.src; }) : [];
      if (!photos.length) return;
      var title = String(c.title || "");
      var id = String(c.id || "categorie");
      if (RESERVED_IDS.indexOf(id) !== -1 || used[id]) id = "cat-" + id;
      used[id] = true;
      var category = { id: id, title: title, items: [] };
      photos.forEach(function (p) {
        var caption = String(p.caption || "");
        var item = {
          index: flat.length,
          // ?v= changes whenever the photo's content changes, so browsers never show a stale copy.
          src: encodeURI(String(p.src)) + (p.v ? "?v=" + encodeURIComponent(String(p.v)) : ""),
          caption: caption,
          categoryTitle: title,
          categoryId: id,
          label: caption ? title + ", " + caption : title
        };
        flat.push(item);
        category.items.push(item);
      });
      categories.push(category);
    });
  })();

  /* ---------- gallery ---------- */
  (function buildGallery() {
    var chips = $(".chips");
    var gallery = $(".gallery");
    if (!flat.length) {
      gallery.appendChild(el("p", "empty", "Aucune photo pour le moment."));
      return;
    }
    var chipFrag = document.createDocumentFragment();
    var galFrag = document.createDocumentFragment();
    categories.forEach(function (c) {
      var count = pad2(c.items.length);

      var chip = el("a", "chip", c.title);
      chip.href = "#" + c.id;
      chip.appendChild(el("span", "chip-count", count));
      chipFrag.appendChild(chip);

      var block = el("div", "category");
      block.id = c.id;
      var h3 = el("h3", "category-title");
      h3.appendChild(icon("i-logo", 0, "category-logo"));
      h3.appendChild(el("span", null, c.title));
      h3.appendChild(el("span", "category-rule"));
      h3.appendChild(el("span", "category-count", count));
      block.appendChild(h3);

      var grid = el("div", "grid");
      c.items.forEach(function (it) {
        var b = el("button", "piece");
        b.type = "button";
        b.setAttribute("aria-label", it.label);
        b.dataset.index = it.index;
        var frame = el("span", "piece-img");
        var img = el("img");
        img.alt = "";
        img.width = 1024;
        img.height = 768;
        img.loading = "lazy";
        img.decoding = "async";
        img.src = it.src;
        frame.appendChild(img);
        b.appendChild(frame);
        var cap = el("span", "piece-cap", it.caption);
        cap.appendChild(icon("i-expand", 16));
        b.appendChild(cap);
        grid.appendChild(b);
      });
      block.appendChild(grid);
      galFrag.appendChild(block);
    });
    chips.appendChild(chipFrag);
    gallery.appendChild(galFrag);

    gallery.addEventListener("click", function (e) {
      var b = e.target.closest(".piece");
      if (b) viewer.open(Number(b.dataset.index), b);
    });
  })();

  /* ---------- slideshow ---------- */
  var slideshow = (function () {
    var fig = document.getElementById("slideshow");
    if (!flat.length) { fig.hidden = true; return { restart: function () {} }; }
    var layers = fig.querySelectorAll(".slideshow-layer");
    var cap = $(".slideshow-cap", fig);
    var progress = $(".slideshow-progress", fig);
    var playBtn = $(".slideshow-play", fig);
    var n = flat.length;
    // Always starts automatically (the client's choice); the pause button stays available.
    var state = { index: 0, playing: true };
    var front = 0;
    var token = 0;
    var timer = null;

    function preload(i) {
      if (n < 2) return;
      var img = new Image();
      img.decoding = "async";
      img.src = flat[(i + 1) % n].src;
    }

    function render(i) {
      var it = flat[i];
      cap.textContent = it.caption || it.categoryTitle;
      progress.style.width = ((i + 1) / n * 100).toFixed(2) + "%";
    }

    function show(i, first) {
      i = (i + n) % n;
      state.index = i;
      render(i);
      var it = flat[i];
      if (first) {
        layers[0].src = it.src;
        layers[0].alt = it.label;
        preload(i);
        return;
      }
      var my = ++token;
      var back = layers[1 - front];
      var swap = function () {
        if (my !== token) return;
        back.onload = back.onerror = null;
        var old = layers[front];
        back.alt = it.label;
        back.removeAttribute("aria-hidden");
        back.classList.add("is-visible");
        old.classList.remove("is-visible");
        old.alt = "";
        old.setAttribute("aria-hidden", "true");
        front = 1 - front;
        preload(i);
      };
      back.onload = back.onerror = swap;
      back.src = it.src;
      if (back.complete && back.naturalWidth) swap();
    }

    function tick() {
      if (!state.playing || isOpen(viewerDlg) || isOpen(menuDlg) || document.hidden) return;
      show(state.index + 1);
    }
    function restart() {
      clearInterval(timer);
      timer = setInterval(tick, SLIDE_MS);
    }
    function setPlaying(p) {
      state.playing = p;
      if (p) playBtn.removeAttribute("data-paused"); else playBtn.setAttribute("data-paused", "");
      playBtn.setAttribute("aria-label", p ? "Mettre le diaporama en pause" : "Lancer le diaporama");
      restart();
    }

    playBtn.addEventListener("click", function () { setPlaying(!state.playing); });
    $(".slideshow-prev", fig).addEventListener("click", function () { show(state.index - 1); restart(); });
    $(".slideshow-next", fig).addEventListener("click", function () { show(state.index + 1); restart(); });

    show(0, true);
    setPlaying(state.playing);
    return { restart: restart };
  })();

  /* ---------- viewer ---------- */
  var viewer = (function () {
    var img = $(".viewer-img", viewerDlg);
    var metas = viewerDlg.querySelectorAll(".viewer-meta");
    var count = $(".viewer-count", viewerDlg);
    var thumbsBox = $(".viewer-thumbs", viewerDlg);
    var closeBtn = $(".viewer-close", viewerDlg);
    var n = flat.length;
    var current = 0;
    var opener = null;
    var thumbs = [];

    function offsets() {
      var k = Math.min(7, n);
      var start = -Math.floor((k - 1) / 2);
      var out = [];
      for (var o = start; o < start + k; o++) out.push(o);
      return out;
    }

    (function buildThumbs() {
      if (n < 2) return;
      offsets().forEach(function (o) {
        var b = el("button", "thumb");
        b.type = "button";
        b.dataset.offset = o;
        var ti = el("img");
        ti.alt = "";
        ti.decoding = "async";
        b.appendChild(ti);
        thumbsBox.appendChild(b);
        thumbs.push(b);
      });
      thumbsBox.addEventListener("click", function (e) {
        var b = e.target.closest(".thumb");
        if (!b) return;
        show(current + Number(b.dataset.offset));
        var center = thumbsBox.querySelector(".thumb[aria-current]");
        if (center) center.focus();
      });
    })();

    function show(i) {
      current = (i + n) % n;
      var it = flat[current];
      img.src = it.src;
      img.alt = it.label;
      viewerDlg.setAttribute("aria-label", it.label);
      for (var m = 0; m < metas.length; m++) {
        $(".viewer-category", metas[m]).textContent = it.categoryTitle;
        $(".viewer-cap", metas[m]).textContent = it.caption;
        metas[m].classList.toggle("no-cap", !it.caption);
      }
      count.textContent = pad2(current + 1) + " / " + n;
      thumbs.forEach(function (b) {
        var o = Number(b.dataset.offset);
        var t = flat[(current + o + n) % n];
        b.firstChild.src = t.src;
        b.setAttribute("aria-label", t.label);
        if (o === 0) b.setAttribute("aria-current", "true"); else b.removeAttribute("aria-current");
      });
    }

    function open(i, from) {
      if (!n) return;
      opener = from || null;
      show(i);
      if (!viewerDlg.open) viewerDlg.showModal();
      closeBtn.focus();
    }

    closeBtn.addEventListener("click", function () { viewerDlg.close(); });
    $(".viewer-prev", viewerDlg).addEventListener("click", function () { show(current - 1); });
    $(".viewer-next", viewerDlg).addEventListener("click", function () { show(current + 1); });
    viewerDlg.addEventListener("keydown", function (e) {
      if (e.key === "ArrowLeft") { e.preventDefault(); show(current - 1); }
      else if (e.key === "ArrowRight") { e.preventDefault(); show(current + 1); }
    });
    viewerDlg.addEventListener("close", function () {
      var back = opener;
      img.removeAttribute("src");
      if (back && document.contains(back)) back.focus();
      opener = null;
      slideshow.restart();
    });

    // Horizontal swipe on the image (mobile)
    var startX = null, startY = 0;
    img.addEventListener("pointerdown", function (e) { startX = e.clientX; startY = e.clientY; });
    img.addEventListener("pointercancel", function () { startX = null; });
    img.addEventListener("pointerup", function (e) {
      if (startX === null) return;
      var dx = e.clientX - startX, dy = e.clientY - startY;
      startX = null;
      if (Math.abs(dx) >= SWIPE_PX && Math.abs(dx) > Math.abs(dy)) show(current + (dx < 0 ? 1 : -1));
    });

    return { open: open };
  })();

  /* ---------- menu (mobile) ---------- */
  (function menu() {
    var btn = $(".menu-btn");
    function sync() { btn.setAttribute("aria-expanded", menuDlg.open ? "true" : "false"); }
    btn.addEventListener("click", function () {
      menuDlg.showModal();
      sync();
      $(".menu-close", menuDlg).focus();
    });
    $(".menu-close", menuDlg).addEventListener("click", function () { menuDlg.close(); });
    menuDlg.addEventListener("close", function () { sync(); slideshow.restart(); });
    menuDlg.querySelectorAll(".menu-nav a[href^='#']").forEach(function (a) {
      a.addEventListener("click", function () { menuDlg.close(); });
    });
  })();

  /* ---------- navSpy ---------- */
  (function navSpy() {
    if (!("IntersectionObserver" in window)) return;
    var links = document.querySelectorAll(".site-header .navlink");
    function setCurrent(id) {
      links.forEach(function (a) {
        if (a.getAttribute("href") === "#" + id) a.setAttribute("aria-current", "true");
        else a.removeAttribute("aria-current");
      });
    }
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (en) { if (en.isIntersecting) setCurrent(en.target.id); });
    }, { rootMargin: "-45% 0px -54% 0px" });
    ["accueil", "realisations", "contacts"].forEach(function (id) {
      var s = document.getElementById(id);
      if (s) io.observe(s);
    });
  })();
})();
